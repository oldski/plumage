// Generates src/primitives/color.tokens.json from scripts/ramps.config.ts.
// Run with `pnpm ramps`. The output is committed: primitives are source, and
// this script is how they were made, so anyone can see and reproduce the method.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { converter } from "culori";
import { format } from "prettier";
import { hexOf, luminance, oklchOf, solveForLuminance } from "./lib/color.ts";
import {
  CHROMATIC_STEPS,
  LUMINANCE_BY_STEP,
  NEUTRAL_STEPS,
  RAMPS,
  chromaFor,
  hueFor,
  type Step,
} from "./ramps.config.ts";

const toRgb = (hex: string) => converter("rgb")(hex)!;
const OUT = fileURLToPath(new URL("../src/primitives/color.tokens.json", import.meta.url));

interface DtcgColor {
  colorSpace: "srgb";
  components: number[];
  alpha?: number;
  hex: string;
}

const round = (n: number, places: number) => Number(n.toFixed(places));

/**
 * sRGB components (exact, so in-gamut by construction) plus the hex. Ramp
 * colors are gamut-mapped and sit on the sRGB boundary, so storing rounded
 * OKLCH components would push some of them just outside it. OKLCH is kept in
 * $extensions for documentation.
 */
function colorToken(hex: string) {
  const { r, g, b } = toRgb(hex);
  const { l, c, h } = oklchOf(hex);
  return {
    $value: {
      colorSpace: "srgb",
      components: [r, g, b].map((n) => round(n, 4)),
      hex,
    } satisfies DtcgColor,
    $extensions: { "dev.plumage": { oklch: [round(l, 4), round(c, 4), round(h, 1)] } },
  };
}

const lerp = (a: number, b: number, t: number) => a + (b - a) * t;

function rampTokens(name: string): Record<string, unknown> {
  const ramp = RAMPS[name]!;
  const group: Record<string, unknown> = { $description: ramp.description };
  const steps: readonly Step[] = ramp.kind === "neutral" ? NEUTRAL_STEPS : CHROMATIC_STEPS;

  steps.forEach((step, index) => {
    const t = index / (steps.length - 1);
    const targetY = LUMINANCE_BY_STEP[step];
    const color =
      ramp.kind === "neutral"
        ? solveForLuminance(targetY, lerp(ramp.chroma[0], ramp.chroma[1], t), ramp.hue)
        : solveForLuminance(
            targetY,
            chromaFor(ramp, step as (typeof CHROMATIC_STEPS)[number]),
            hueFor(ramp, step as (typeof CHROMATIC_STEPS)[number], t),
          );
    const hex = hexOf(color);
    const drift = Math.abs(luminance(hex) - targetY) / targetY;
    if (drift > 0.03) {
      throw new Error(
        `${name}.${step}: luminance drifted ${(drift * 100).toFixed(1)}% after rounding`,
      );
    }
    group[String(step)] = colorToken(hex);
  });
  return group;
}

function alphaTokens(base: "black" | "white"): Record<string, unknown> {
  const components = base === "black" ? [0, 0, 0] : [1, 1, 1];
  const hex = base === "black" ? "#000000" : "#ffffff";
  const group: Record<string, unknown> = {
    $description: `${base === "black" ? "Black" : "White"} at fixed opacities, for scrims, shadows, and tints that work on any surface.`,
  };
  for (const pct of [4, 8, 12, 16, 24, 48, 64]) {
    group[String(pct)] = {
      $value: { colorSpace: "srgb", components, alpha: pct / 100, hex } satisfies DtcgColor,
    };
  }
  return group;
}

const ramps = Object.fromEntries(Object.keys(RAMPS).map((name) => [name, rampTokens(name)]));

const tokens = {
  $schema: "https://www.designtokens.org/schemas/2025.10/format.json",
  color: {
    $type: "color",
    $description:
      "Primitive color. Raw values with no meaning attached. Components never reference these directly. Generated by scripts/generate-ramps.ts; do not edit by hand.",
    white: { $value: { colorSpace: "srgb", components: [1, 1, 1], hex: "#ffffff" } },
    black: { $value: { colorSpace: "srgb", components: [0, 0, 0], hex: "#000000" } },
    "black-alpha": alphaTokens("black"),
    "white-alpha": alphaTokens("white"),
    ...ramps,
  },
};

writeFileSync(OUT, await format(JSON.stringify(tokens), { parser: "json", printWidth: 100 }));

// Print a compact table so the result can be reviewed in the terminal.
for (const [name, ramp] of Object.entries(ramps)) {
  const row = Object.entries(ramp)
    .filter(([k]) => !k.startsWith("$"))
    .map(([step, t]) => `${step}:${(t as { $value: DtcgColor }).$value.hex}`)
    .join(" ");
  console.log(`${name.padEnd(7)} ${row}`);
}
console.log(`\nWrote ${OUT}`);
