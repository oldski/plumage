// Terrazzo plugin for the outputs plugin-css does not cover: the Tailwind v4
// theme, typed TypeScript exports, Figma variable collections, and a manifest
// that the docs site renders. Everything is derived from the resolver.
import type { Plugin, TokenNormalized, TokenNormalizedSet } from "@terrazzo/parser";
import { transformCSSValue } from "@terrazzo/token-tools/css";
import { converter, parse } from "culori";
import {
  FIGMA_COLLECTION,
  MODIFIERS,
  aliasTarget,
  isPublic,
  loadSource,
  tierOf,
  type Layer,
  type Modifier,
  type SourceMap,
} from "./source.ts";
import { cssVarName, exampleUtility, tailwindMergeConfig, tailwindVars } from "./naming.ts";

const HEADER = "Generated by @plumage/tokens from src/plumage.resolver.json. Do not edit.";
const toRgb = converter("rgb");

type Input = Record<Modifier, string>;
const permutationKey = (i: Input) => `${i.brand}/${i.mode}/${i.density}`;

/** Every full combination of brand, mode, and density. */
function allInputs(source: SourceMap): Input[] {
  const out: Input[] = [];
  for (const brand of source.contexts.brand)
    for (const mode of source.contexts.mode)
      for (const density of source.contexts.density) out.push({ brand, mode, density });
  return out;
}

/** CSS value of a token with every alias followed to the end (no var()). */
function resolvedCSS(token: TokenNormalized, set: TokenNormalizedSet, input: Input): string {
  const value = transformCSSValue(token, {
    tokensSet: set,
    permutation: input,
    transformAlias: (t) => resolvedCSS(t, set, input),
    color: { legacyHex: true },
  });
  const css = typeof value === "string" ? value : (value["."] ?? Object.values(value)[0] ?? "");
  return expandHex(css);
}

/** "#fff" -> "#ffffff", "#0008" -> "#00000088", so consumers always get 6 or 8 digits. */
function expandHex(css: string): string {
  return /^#[0-9a-f]{3,4}$/i.test(css) ? `#${css.slice(1).replace(/./g, "$&$&")}` : css;
}

function tailwindTheme(source: SourceMap): string {
  const lines: string[] = [];
  for (const token of source.tokens.values()) {
    if (!isPublic(token)) continue;
    for (const themeVar of tailwindVars(token.id)) {
      lines.push(`  ${themeVar}: var(${cssVarName(token.id)});`);
    }
  }
  return `/* ${HEADER}
 *
 * Tailwind v4 theme for Plumage. Import order:
 *   @import "tailwindcss";
 *   @import "@plumage/tokens/css";
 *   @import "@plumage/tokens/tailwind.css";
 *
 * Tailwind's default palette and scales are switched off, so only
 * token-backed utilities exist: bg-surface, text-muted, border-strong,
 * rounded-control, h-control-md, px-control-md, gap-sm, text-body, and so
 * on. Utilities point at runtime CSS variables (@theme inline), so changing
 * data-brand, data-theme, or data-density restyles them with no rebuild.
 */

@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *));

@theme {
  --color-*: initial;
  --font-*: initial;
  --font-weight-*: initial;
  --text-*: initial;
  --radius-*: initial;
  --shadow-*: initial;
  --inset-shadow-*: initial;
  --drop-shadow-*: initial;
  --ease-*: initial;
  --animate-*: initial;
  --spacing-*: initial;
  /* Zero is not a design value: keep p-0, inset-0, min-w-0 and friends. */
  --spacing-0: 0px;
}

@theme inline {
${lines.join("\n")}
}
`;
}

interface Built {
  source: SourceMap;
  types: Record<string, string>;
  values: Record<string, Record<string, string>>;
  primitives: Record<string, string>;
}

function typescript({ source, types, values, primitives }: Built): { js: string; dts: string } {
  const publicIds = [...source.tokens.values()].filter(isPublic).map((t) => t.id);
  const cssVars = Object.fromEntries(publicIds.map((id) => [id, cssVarName(id)]));
  const union = (ids: string[]) =>
    ids.length ? ids.map((id) => `  | "${id}"`).join("\n") : "never";
  const byType = (type: string) => publicIds.filter((id) => types[id] === type);
  const lit = (xs: string[]) => xs.map((x) => `"${x}"`).join(" | ");
  const mergeConfig = tailwindMergeConfig(publicIds.flatMap(tailwindVars));

  const js = `// ${HEADER}
export const brands = ${JSON.stringify(source.contexts.brand)};
export const modes = ${JSON.stringify(source.contexts.mode)};
export const densities = ${JSON.stringify(source.contexts.density)};
export const defaults = ${JSON.stringify({ mode: source.defaults.mode, density: source.defaults.density })};
export const attributes = { brand: "data-brand", mode: "data-theme", density: "data-density" };
export const brandDefaults = ${JSON.stringify(source.brandDefaults)};
export const brandNames = ${JSON.stringify(source.brandNames)};
export const tailwindMergeConfig = ${JSON.stringify(mergeConfig, null, 2)};
export const cssVars = ${JSON.stringify(cssVars, null, 2)};
export function cssVar(name) {
  const v = cssVars[name];
  if (!v) throw new Error(\`Unknown Plumage token: \${name}\`);
  return \`var(\${v})\`;
}
export const values = ${JSON.stringify(values, null, 2)};
export const primitives = ${JSON.stringify(primitives, null, 2)};
export function resolve(name, { brand, mode = defaults.mode, density = brandDefaults[brand]?.density }) {
  const v = values[\`\${brand}/\${mode}/\${density}\`]?.[name];
  if (v === undefined) throw new Error(\`No value for \${name} in \${brand}/\${mode}/\${density}\`);
  return v;
}
`;

  const dts = `// ${HEADER}
export type Brand = ${lit(source.contexts.brand)};
export type Mode = ${lit(source.contexts.mode)};
export type Density = ${lit(source.contexts.density)};
export type Permutation = \`\${Brand}/\${Mode}/\${Density}\`;

/** Every public token: the semantic and component tiers. */
export type TokenName =
${union(publicIds)};
export type ColorTokenName =
${union(byType("color"))};
export type DimensionTokenName =
${union(byType("dimension"))};
export type PrimitiveTokenName =
${union(source.idsByLayer.primitive)};

export declare const brands: readonly Brand[];
export declare const modes: readonly Mode[];
export declare const densities: readonly Density[];
export declare const defaults: { readonly mode: Mode; readonly density: Density };
export declare const attributes: {
  readonly brand: "data-brand";
  readonly mode: "data-theme";
  readonly density: "data-density";
};
/** Per-brand defaults: Finch is compact, Sparrow comfortable. */
export declare const brandDefaults: { readonly [B in Brand]: { readonly density: Density } };
/** Human-readable brand names, e.g. "Sparrow". */
export declare const brandNames: { readonly [B in Brand]: string };
/** Pass to extendTailwindMerge({ extend: tailwindMergeConfig }) so cn() understands Plumage utilities. */
export declare const tailwindMergeConfig: {
  readonly theme: Readonly<Record<string, string[]>>;
  readonly classGroups: Readonly<Record<string, [Record<string, string[]>]>>;
};
/** CSS custom property name per token, e.g. "--pl-color-bg-surface". */
export declare const cssVars: { readonly [K in TokenName]: \`--pl-\${string}\` };
/** var() reference for use in inline styles or SVG, e.g. cssVar("color.chart.categorical.1"). */
export declare function cssVar(name: TokenName): \`var(--pl-\${string})\`;
/** Fully resolved CSS values for every permutation, for canvases, exports, docs, and tests. */
export declare const values: { readonly [P in Permutation]: { readonly [K in TokenName]: string } };
export declare const primitives: { readonly [K in PrimitiveTokenName]: string };
/** Resolved value of a token. Density defaults to the brand's default density. */
export declare function resolve(
  name: TokenName,
  scope: { brand: Brand; mode?: Mode; density?: Density },
): string;
`;
  return { js, dts };
}

// Figma variables cover color, number, and string. Dimensions become px
// numbers; composites (shadow, cubicBezier) and durations stay in code.
function figmaValue(
  token: TokenNormalized,
  css: string,
): { $type: string; $value: unknown } | undefined {
  switch (token.$type) {
    case "color": {
      const c = toRgb(parse(css)!);
      const round = (n: number) => Number(n.toFixed(4));
      return {
        $type: "color",
        $value: {
          colorSpace: "srgb",
          components: [round(c.r), round(c.g), round(c.b)],
          ...(c.alpha !== undefined && c.alpha < 1 ? { alpha: round(c.alpha) } : {}),
          hex: css.slice(0, 7),
        },
      };
    }
    case "dimension": {
      const m = /^(-?[\d.]+)(px|rem)$/.exec(css);
      if (!m) return undefined;
      const px = m[2] === "rem" ? Number(m[1]) * 16 : Number(m[1]);
      return { $type: "dimension", $value: { value: px, unit: "px" } };
    }
    case "number":
    case "fontWeight":
      return { $type: "number", $value: Number(css) };
    case "fontFamily":
      return { $type: "string", $value: css.split(",")[0]!.replaceAll('"', "").trim() };
    default:
      return undefined;
  }
}

function setPath(root: Record<string, unknown>, id: string, leaf: unknown) {
  const parts = id.split(".");
  let node = root;
  for (const p of parts.slice(0, -1)) node = (node[p] ??= {}) as Record<string, unknown>;
  node[parts.at(-1)!] = leaf;
}

/** The modifier layer a token's value depends on, following aliases. */
function dependsOn(source: SourceMap, id: string, seen = new Set<string>()): Layer {
  const token = source.tokens.get(id);
  if (!token || seen.has(id)) return "primitive";
  if (token.layer !== "component") return token.layer;
  seen.add(id);
  const target = aliasTarget(Object.values(token.raw)[0]);
  return target ? dependsOn(source, target, seen) : "primitive";
}

function figma(source: SourceMap, defaultSet: TokenNormalizedSet, input: Input) {
  const files: Record<string, Record<string, unknown>> = {};
  const emit = (collection: string, mode: string, id: string, raw: unknown) => {
    const token = defaultSet[id];
    if (!token) return;
    const target = aliasTarget(raw);
    const value = figmaValue(token, resolvedCSS(token, defaultSet, input));
    if (!value) return;
    const file = (files[`${collection}/${mode}.tokens.json`] ??= {});
    setPath(file, id, {
      $type: value.$type,
      $value: target ? `{${target}}` : value.$value,
      ...(token.$description ? { $description: token.$description } : {}),
    });
  };
  for (const id of source.idsByLayer.primitive)
    emit(FIGMA_COLLECTION.primitive, "Value", id, undefined);
  for (const modifier of MODIFIERS) {
    for (const id of source.idsByLayer[modifier]) {
      const token = source.tokens.get(id)!;
      for (const context of source.contexts[modifier]) {
        emit(FIGMA_COLLECTION[modifier], context, id, token.raw[context]);
      }
    }
  }
  // Component tokens join the collection they vary with, same alias in every mode.
  for (const id of source.idsByLayer.component) {
    const token = source.tokens.get(id)!;
    const layer = dependsOn(source, id);
    const collection = layer === "component" ? "primitive" : layer;
    const modesOf = collection === "primitive" ? ["Value"] : source.contexts[collection];
    for (const mode of modesOf) emit(FIGMA_COLLECTION[collection], mode, id, token.raw["."]);
  }
  return files;
}

export default function plumage(): Plugin {
  return {
    name: "plumage",
    build({ resolver, outputFile }) {
      const source = loadSource();
      const inputs = allInputs(source);
      const defaultInput: Input = { ...source.defaults };
      const defaultSet = resolver.apply(defaultInput);

      const types: Record<string, string> = {};
      for (const [id, token] of Object.entries(defaultSet)) types[id] = token.$type;

      const values: Built["values"] = {};
      for (const input of inputs) {
        const set = resolver.apply(input);
        const row: Record<string, string> = {};
        for (const token of source.tokens.values()) {
          if (!isPublic(token)) continue;
          const t = set[token.id];
          if (t) row[token.id] = resolvedCSS(t, set, input);
        }
        values[permutationKey(input)] = row;
      }
      const primitives: Record<string, string> = {};
      for (const id of source.idsByLayer.primitive) {
        const t = defaultSet[id];
        if (t) primitives[id] = resolvedCSS(t, defaultSet, defaultInput);
      }

      outputFile("tailwind.css", tailwindTheme(source));

      const { js, dts } = typescript({ source, types, values, primitives });
      outputFile("index.js", js);
      outputFile("index.d.ts", dts);

      for (const [path, json] of Object.entries(figma(source, defaultSet, defaultInput))) {
        outputFile(`figma/${path}`, `${JSON.stringify(json, null, 2)}\n`);
      }

      const manifest = {
        $comment: HEADER,
        prefix: "--pl-",
        attributes: { brand: "data-brand", mode: "data-theme", density: "data-density" },
        contexts: source.contexts,
        defaults: source.defaults,
        tokens: Object.fromEntries(
          [...source.tokens.values()].map((t) => {
            const themeVars = isPublic(t) ? tailwindVars(t.id) : [];
            return [
              t.id,
              {
                type: types[t.id],
                tier: tierOf(t),
                layer: t.layer,
                cssVar: cssVarName(t.id),
                description: t.description ?? defaultSet[t.id]?.$description,
                aliases: Object.fromEntries(
                  Object.entries(t.raw).flatMap(([ctx, raw]) => {
                    const target = aliasTarget(raw);
                    return target ? [[ctx, target]] : [];
                  }),
                ),
                tailwind: themeVars,
                utilities: themeVars.map(exampleUtility).filter(Boolean),
              },
            ];
          }),
        ),
      };
      outputFile("manifest.json", `${JSON.stringify(manifest, null, 2)}\n`);
    },
  };
}
